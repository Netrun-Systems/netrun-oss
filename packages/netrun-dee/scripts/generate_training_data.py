def _intensity_to_level(intensity: float) -> str:
    if intensity <= 1.0:
        return 'subtle'
    elif intensity <= 2.0:
        return 'moderate'
    return 'strong'


def generate_single_label_sample(profile_id: str, intensity_level: str) -> dict:
    """Generate one training sample for a single DEE profile."""
    register = random.choice(['professional', 'casual'])
    templates = PROFESSIONAL_TEMPLATES if register == 'professional' else CASUAL_TEMPLATES
    template_list = templates[intensity_level]
    template = random.choice(template_list)

    # Count how many pattern slots are in the template
    slot_count = template.count('{p')
    fragments = _get_lexicon_fragments(profile_id, max(slot_count, 1))

    # Fill slots
    text = template
    for i, frag in enumerate(fragments[:slot_count], 1):
        text = text.replace(f'{{p{i}}}', frag, 1)

    # Intensity value: subtle=0.5-1.0, moderate=1.0-2.0, strong=2.0-3.0
    intensity_ranges = {
        'subtle': (0.5, 1.0),
        'moderate': (1.0, 2.0),
        'strong': (2.0, 3.0),
    }
    lo, hi = intensity_ranges[intensity_level]
    intensity = round(random.uniform(lo, hi), 1)

    return {
        'text': text,
        'labels': {profile_id: intensity},
        'intensity_level': intensity_level,
    }


def generate_multi_label_sample(combo_idx: int) -> dict:
    """Generate a multi-label sample from predefined combinations."""
    profile_ids, template = MULTI_LABEL_COMBOS[combo_idx]

    # Get fragments for each profile
    all_fragments = []
    for pid in profile_ids:
        frags = _get_lexicon_fragments(pid, 2)
        all_fragments.extend(frags)

    random.shuffle(all_fragments)

    # Fill template slots
    text = template
    slot_count = template.count('{p')
    for i, frag in enumerate(all_fragments[:slot_count], 1):
        text = text.replace(f'{{p{i}}}', frag, 1)

    # Assign intensities — the primary is stronger
    labels = {}
    for i, pid in enumerate(profile_ids):
        if i == 0:
            labels[pid] = round(random.uniform(1.5, 3.0), 1)
        else:
            labels[pid] = round(random.uniform(0.5, 2.0), 1)

    return {
        'text': text,
        'labels': labels,
        'intensity_level': 'strong' if max(labels.values()) > 2.0 else 'moderate',
    }


def generate_dataset(samples_per_profile: int = 50, seed: int = 42) -> list[dict]:
    """Generate the full synthetic training dataset.

    For each of the 39 profiles:
    - ~1/3 subtle intensity
    - ~1/3 moderate intensity
    - ~1/3 strong intensity

    Plus multi-label combination samples.

    Args:
        samples_per_profile: Number of single-label samples per profile.
        seed: Random seed for reproducibility.

    Returns:
        List of training sample dicts.
    """
    random.seed(seed)
    samples = []

    # Single-label samples
    for profile in DEE_PROFILES_LIST:
        subtle_count = samples_per_profile // 3
        moderate_count = samples_per_profile // 3
        strong_count = samples_per_profile - subtle_count - moderate_count

        for _ in range(subtle_count):
            samples.append(generate_single_label_sample(profile.id, 'subtle'))
        for _ in range(moderate_count):
            samples.append(generate_single_label_sample(profile.id, 'moderate'))
        for _ in range(strong_count):
            samples.append(generate_single_label_sample(profile.id, 'strong'))

    # Multi-label samples: 5 samples per combination
    for combo_idx in range(len(MULTI_LABEL_COMBOS)):
        for _ in range(5):
            samples.append(generate_multi_label_sample(combo_idx))

    random.shuffle(samples)
    return samples


def main():
    parser = argparse.ArgumentParser(description='Generate synthetic DEE training data')
    parser.add_argument('--count', type=int, default=50,
                        help='Samples per profile (default: 50)')
    parser.add_argument('--output', type=str, default='/tmp/dee_training_samples.jsonl',
                        help='Output JSONL file path')
    parser.add_argument('--seed', type=int, default=42,
                        help='Random seed for reproducibility')
    args = parser.parse_args()

    samples = generate_dataset(samples_per_profile=args.count, seed=args.seed)

    # Write JSONL
    with open(args.output, 'w') as f:
        for sample in samples:
            f.write(json.dumps(sample) + '\n')

    # Summary stats
    single_label = sum(1 for s in samples if len(s['labels']) == 1)
    multi_label = sum(1 for s in samples if len(s['labels']) > 1)

    # Per-profile counts
    profile_counts: dict[str, int] = {}
    for s in samples:
        for pid in s['labels']:
            profile_counts[pid] = profile_counts.get(pid, 0) + 1

    print(f"Generated {len(samples)} training samples")
    print(f"  Single-label: {single_label}")
    print(f"  Multi-label:  {multi_label}")
    print(f"  Profiles covered: {len(profile_counts)}/39")
    print(f"  Output: {args.output}")

    # Intensity distribution
    levels = {'subtle': 0, 'moderate': 0, 'strong': 0}
    for s in samples:
        levels[s['intensity_level']] += 1
    print(f"  Intensity distribution: {levels}")


if __name__ == '__main__':
    main()
