# --- Phrase expansions: convert lexicon patterns into natural sentence fragments ---

def _expand_pattern(entry: LexiconEntry) -> str:
    """Turn a lexicon entry into a natural sentence fragment."""
    p = entry.pattern

    if entry.is_regex:
        # Convert regex patterns to concrete examples
        REGEX_EXPANSIONS = {
            r'!{2,}': 'the results were incredible!!',
            r'[A-Z]{3,}\b': 'this is CRITICAL',
            r'[FfDd]\s*grade': 'we got a D grade on this',
            r'flagged\s+\d+\s*times?': 'this has been flagged 3 times',
            r'\?{2,}': 'how did this happen??',
            r'\d+\s*days?\s*stale': 'the data is 10 days stale',
            r'\d+\s*days?\s*since': 'it has been 14 days since the last update',
            r';\)': 'you know what I mean ;)',
            r':\)': 'sounds good :)',
        }
        return REGEX_EXPANSIONS.get(p, f'the {p} pattern was detected')

    # For plain keywords/phrases, wrap in plausible context fragments
    if entry.category == 'keyword':
        KEYWORD_FRAMES = [
            f"the situation is {p}",
            f"this feels {p}",
            f"I would describe it as {p}",
            f"the word that comes to mind is {p}",
            f"things are looking {p}",
            f"the response was {p}",
            f"it was genuinely {p}",
            f"what stands out is how {p} this is",
        ]
        return random.choice(KEYWORD_FRAMES)

    # Phrases can often stand alone or with light framing
    PHRASE_FRAMES = [
        f"{p}",
        f"we {p}",
        f"I {p}",
        f"the team {p}",
        f"it's clear that {p}",
        f"as it turns out, {p}",
    ]
    return random.choice(PHRASE_FRAMES)


def _get_lexicon_fragments(profile_id: str, count: int) -> list[str]:
    """Get N random expanded lexicon fragments for a profile."""
    entries = DEE_LEXICONS.get(profile_id, [])
    if not entries:
        return []

    # Weight selection by entry weight (higher weight = more likely to be selected)
    weights = [e.weight for e in entries]
    selected = random.choices(entries, weights=weights, k=count)
    return [_expand_pattern(e) for e in selected]


